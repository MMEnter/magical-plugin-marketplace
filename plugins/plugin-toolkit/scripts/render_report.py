#!/usr/bin/env python3
"""Render a merged findings JSON into report.md plus a patches/ folder.

Usage:
  render_report.py FINDINGS_JSON --out DIR [--plugin PLUGIN_DIR] [--mode review|security]

The findings file is the synthesizer's merged output (references/finding-schema.md).
This script never invents findings; it validates the JSON, writes each finding's patch
to patches/<id>-<rule>-<slug>.diff, checks every patch with `git apply --check` when
--plugin is given, and renders the report from fixed templates (HR-P01, HR-P04).

Prints the report ID (rv-... or sc-...). Exit 0 ok, 1 invalid findings, 2 usage error.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import validate_plugin as vp  # noqa: E402

# Fixed boilerplate (HR-P04): never regenerated by the model.
HEADER = {
    "review": "Plugin review",
    "security": "Plugin security review",
}
INTRO = ("Generated by plugin-toolkit from the panel's merged findings. Rules are defined in "
         "`references/plugin-guidelines.md` and `references/security-checklist.md`. "
         "Nothing in the plugin has been changed; patches are applied only by fix-plugin after approval.")
SEVERITY_ORDER = {"critical": 0, "major": 1, "minor": 2}
STATUS_ORDER = {"open": 0, "disputed": 1, "waived": 2, "fixed": 3}
REQUIRED = ("id", "rule", "severity", "kind", "analyst", "status", "title", "evidence", "fix")


def validate_findings(data: dict, rules: dict) -> list[str]:
    errs = []
    if data.get("schema_version") != 1:
        errs.append("schema_version must be 1")
    if data.get("mode") not in ("review", "security", "mechanical"):
        errs.append("mode must be review, security or mechanical")
    ids = set()
    for i, f in enumerate(data.get("findings", [])):
        where = f"finding {f.get('id', i)}"
        for k in REQUIRED:
            if k not in f:
                errs.append(f"{where}: missing {k}")
        if f.get("id") in ids:
            errs.append(f"{where}: duplicate id")
        ids.add(f.get("id"))
        rule = rules.get(f.get("rule"))
        if rule is None:
            errs.append(f"{where}: unknown rule {f.get('rule')!r}")
            continue
        if f.get("severity") not in SEVERITY_ORDER:
            errs.append(f"{where}: bad severity")
        elif SEVERITY_ORDER[f["severity"]] > SEVERITY_ORDER[rule["severity"]]:
            errs.append(f"{where}: severity {f['severity']} is below the rule's {rule['severity']}")
        elif SEVERITY_ORDER[f["severity"]] < SEVERITY_ORDER[rule["severity"]] and not f.get("escalation"):
            errs.append(f"{where}: severity raised above the rule's without an escalation reason")
        if f.get("status") not in STATUS_ORDER:
            errs.append(f"{where}: bad status")
        if f.get("status") == "waived" and rule["tier"] != "waivable":
            errs.append(f"{where}: {f['rule']} is mandatory and cannot be waived")
    return errs


def slug(text: str) -> str:
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", text.lower())).strip("-")[:40] or "fix"


def check_patch(patch: Path, plugin: Path) -> tuple[bool, str]:
    env = dict(os.environ, GIT_CEILING_DIRECTORIES=str(plugin.resolve().parent))
    r = subprocess.run(["git", "apply", "--check", "-p1", str(patch.resolve())], cwd=plugin,
                       capture_output=True, text=True, env=env)
    return r.returncode == 0, r.stderr.strip()[:300]


def render(data: dict, rules: dict, patch_status: dict, report_id: str) -> str:
    mode = data.get("mode", "review")
    f_all = sorted(data["findings"], key=lambda f: (STATUS_ORDER[f["status"]], SEVERITY_ORDER[f["severity"]], f["id"]))
    counts = {s: {st: 0 for st in STATUS_ORDER} for s in SEVERITY_ORDER}
    for f in f_all:
        counts[f["severity"]][f["status"]] += 1
    src = data.get("source") or {}
    out = [f"# {HEADER.get(mode, 'Plugin review')}: {data.get('plugin')} {data.get('plugin_version') or ''}".rstrip(),
           "", INTRO, "",
           "| | |", "|---|---|",
           f"| Report | `{report_id}` |",
           f"| Source | {src.get('type', 'local')}: {src.get('location', '-')} |",
           f"| Commit | {src.get('sha') or 'n/a'} |",
           f"| Tree hash | {src.get('tree_hash') or 'n/a'} |",
           f"| Generated | {_dt.datetime.now(_dt.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} |",
           "", "## Summary", "", "| Severity | Open | Disputed | Waived | Fixed |", "|---|---|---|---|---|"]
    for s in SEVERITY_ORDER:
        c = counts[s]
        out.append(f"| {s} | {c['open']} | {c['disputed']} | {c['waived']} | {c['fixed']} |")
    blocking = counts["critical"]["open"] + counts["critical"]["disputed"]
    out += ["", ("**Release is blocked** by %d open or disputed critical finding(s)." % blocking) if blocking
            else "No open critical findings.", ""]
    for status, title in (("open", "Open findings"), ("disputed", "Disputed findings (you decide)"),
                          ("waived", "Waived"), ("fixed", "Fixed")):
        group = [f for f in f_all if f["status"] == status]
        if not group:
            continue
        out += [f"## {title}", ""]
        for f in group:
            rule = rules[f["rule"]]
            loc = f"`{f['file']}:{f['line']}`" if f.get("line") else (f"`{f['file']}`" if f.get("file") else "plugin-wide")
            out += [f"### {f['id']} · {f['severity']} · {f['rule']}: {f['title']}", "",
                    f"- **Where:** {loc}",
                    f"- **Rule:** {rule['text']} ({rule['kind']}, {rule['tier']})",
                    f"- **Found by:** {f['analyst']}",
                    f"- **Evidence:** {f['evidence']}",
                    f"- **Fix:** {f['fix']}"]
            if f.get("escalation"):
                e = f["escalation"]
                out.append(f"- **Escalated** {e.get('from')} → {e.get('to')}: {e.get('reason')}")
            for d in f.get("dissent") or []:
                out.append(f"- **Dissent:** {d}")
            ps = patch_status.get(f["id"])
            if ps:
                state = "applies cleanly" if ps["applies"] is True else (
                    "does not apply: " + ps["error"] if ps["applies"] is False else "not checked")
                out.append(f"- **Patch:** `{ps['file']}` ({state})")
            out.append("")
    for n in data.get("notes", []) or []:
        out.append(f"- Note: {n}")
    out += ["## Next steps", "",
            "1. Decide on any disputed findings.",
            "2. Approve the patches you want; fix-plugin applies them and re-validates.",
            "3. Re-run the review on the fixed plugin, then release-plugin stamps it and opens the pull request.", ""]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("findings")
    ap.add_argument("--out", required=True)
    ap.add_argument("--plugin")
    ap.add_argument("--mode", choices=["review", "security"])
    a = ap.parse_args(argv)
    raw = Path(a.findings).read_bytes()
    data = json.loads(raw)
    if a.mode:
        data["mode"] = a.mode
    rules = vp.load_rules()
    errs = validate_findings(data, rules)
    if errs:
        print("findings file is invalid:", file=sys.stderr)
        for e in errs:
            print(f"  - {e}", file=sys.stderr)
        return 1
    out = Path(a.out)
    (out / "patches").mkdir(parents=True, exist_ok=True)
    statuses = {}
    for f in data["findings"]:
        if not f.get("patch"):
            continue
        name = f"{f['id']}-{f['rule'].lower()}-{slug(f['title'])}.diff"
        p = out / "patches" / name
        p.write_text(f["patch"] if f["patch"].endswith("\n") else f["patch"] + "\n", encoding="utf-8")
        ok, err = (check_patch(p, Path(a.plugin)) if a.plugin else (None, ""))
        statuses[f["id"]] = {"file": f"patches/{name}", "applies": ok, "error": err}
        f["patch_file"] = f"patches/{name}"
        f["patch_applies"] = ok
    prefix = "sc" if data["mode"] == "security" else "rv"
    rid = f"{prefix}-{_dt.date.today().strftime('%Y%m%d')}-{hashlib.sha256(raw).hexdigest()[:8]}"
    data["report_id"] = rid
    open_ = [f for f in data["findings"] if f["status"] == "open"]
    data["summary"] = {s: sum(1 for f in open_ if f["severity"] == s) for s in SEVERITY_ORDER}
    (out / "findings.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    (out / "report.md").write_text(render(data, rules, statuses, rid), encoding="utf-8")
    print(rid)
    return 0


if __name__ == "__main__":
    sys.exit(main())
